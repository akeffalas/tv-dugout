/** The bundled plays (spec 0009), basics first, each tier from simplest to hardest. */
object PlayLibrary {
    val plays: List<Play> = BASICS + SITUATIONS

    private val byId = plays.associateBy { it.id }

    fun play(id: String): Play? = byId[id]

    /** The plays that suit a child of [ageRange]. */
    fun poolFor(ageRange: AgeRange): List<Play> =
        plays.filter { it.tier.ages.first <= ageRange.years.last && ageRange.years.first <= it.tier.ages.last }
}

private fun throwPlay(
    id: String,
    tier: Tier,
    position: Position,
    outs: Int,
    runners: Set<Base>,
    prompt: String,
    answer: Answer,
    why: String,
    ballTo: Position = position,
    caught: Boolean = false,
    rightStamp: Stamp? = OUT,
    wrong: Map<Answer, Stamp> = emptyMap(),
    kind: PlayKind = PlayKind.THROW,
    steal: Base? = null,
) = Play(
    id,
    tier,
    kind,
    Role.Fielder(position),
    outs,
    runners,
    ballTo,
    caught,
    prompt,
    answer,
    rightStamp,
    why,
    wrong,
    steal,
)

private fun runPlay(
    id: String,
    tier: Tier,
    base: Base,
    outs: Int,
    runners: Set<Base>,
    ballTo: Position,
    caught: Boolean,
    prompt: String,
    answer: Answer,
    why: String,
    rightStamp: Stamp? = SAFE,
    wrong: Map<Answer, Stamp> = emptyMap(),
) = Play(
    id,
    tier,
    PlayKind.RUN,
    Role.Runner(base),
    outs,
    runners + base,
    ballTo,
    caught,
    prompt,
    answer,
    rightStamp,
    why,
    wrong,
)

private fun backUpPlay(
    id: String,
    position: Position,
    outs: Int,
    runners: Set<Base>,
    ballTo: Position,
    prompt: String,
    answer: Answer,
    why: String,
    steal: Base? = null,
) = throwPlay(
    id,
    Tier.SITUATIONS,
    position,
    outs,
    runners,
    prompt,
    answer,
    why,
    ballTo = ballTo,
    rightStamp = null,
    kind = PlayKind.BACK_UP,
    steal = steal,
)

